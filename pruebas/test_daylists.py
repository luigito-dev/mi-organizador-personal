from playwright.sync_api import sync_playwright
R=[]
def ok(n,c,x=''): R.append(c); print(('PASS ' if c else 'FAIL ')+n+('' if c else ' -- '+str(x)))
with sync_playwright() as p:
  b=p.chromium.launch()
  for lab,kw in [('tel',dict(p.devices['Pixel 7'])),('pc',{'viewport':{'width':1366,'height':860}})]:
    ctx=b.new_context(**kw); pg=ctx.new_page(); errs=[]; pg.on('pageerror',lambda e: errs.append(str(e)))
    tap=(lambda s: pg.tap(s)) if lab=='tel' else (lambda s: pg.click(s))
    pg.goto('file:///home/claude/org/index.html'); pg.wait_for_timeout(300)
    pg.evaluate("""S.settings.tutorialSeen=true;sheets.slice().forEach(s=>s.close());const t=todayISO();
      const T=(id,title,pr,time,st,date)=>({id,title,date:date||t,time:time||null,typeId:'pendiente',areaId:null,priority:pr||'Media',details:'',steps:[],status:st||'Pendiente',obs:'',reminder:null,createdAt:1});
      S.tasks.push(T('a','Compras del supermercado'),T('b','Recorte de pelo','Urgente','11:00'),T('c','Sacar dinero','Alta'),T('d','Llamar a mamá','Media',null,'Completada'),T('e','Pagar la luz','Media',null,null,addDays(t,-2)));
      S.lists.push({id:'c',name:'Compras',icon:'🛒',color:'#2e9d5b',items:[{id:'1',t:'Leche',done:false},{id:'2',t:'Pan',done:false},{id:'3',t:'Huevos',done:true}]});save();go('dia')""")
    pg.wait_for_timeout(300)
    ok(f'[{lab}] botón con número', pg.locator('#lsBadge').inner_text()=='6')
    tap('#lsBtn'); pg.wait_for_timeout(350)
    ok(f'[{lab}] tarjeta flotante', pg.locator('.ov.float .qcard').count()==1)
    ok(f'[{lab}] HOY con contador', pg.locator('.qtitle').inner_text()=='HOY' and pg.locator('.qcount').inner_text()=='1/5', pg.locator('.qcount').inner_text())
    ok(f'[{lab}] importantes resaltadas', pg.locator('.qrow.r').count()==2 and pg.locator('.qrow.o').count()==1)
    pg.screenshot(path=f'shots/{lab}-qhoy.png')
    tap('.qrow >> text=Sacar dinero'); pg.wait_for_timeout(400)
    ok(f'[{lab}] marcar en HOY', pg.evaluate("S.tasks.find(t=>t.id==='c').status")=='Completada' and pg.locator('.qcount').inner_text()=='2/5')
    pg.fill('#dlAdd','cita con el dentista a las 3 pm'); pg.press('#dlAdd','Enter'); pg.wait_for_timeout(300)
    ok(f'[{lab}] añadir para hoy', pg.evaluate("S.tasks.some(t=>t.title.includes('dentista') && t.time==='15:00')") and pg.locator('.qcount').inner_text()=='2/6')
    pg.evaluate("UI.popTab='c';dayLists(document.querySelector('#lsPop')||document.querySelector('.qcard .sh-body > div'))"); pg.wait_for_timeout(300)
    ok(f'[{lab}] pestaña lista', pg.locator('.qtitle').inner_text()=='COMPRAS' and pg.locator('.qcount').inner_text()=='1/3')
    pg.screenshot(path=f'shots/{lab}-qlista.png')
    tap('.qrow >> text=Leche'); pg.wait_for_timeout(400)
    ok(f'[{lab}] marcar en lista', pg.evaluate("S.lists[0].items[0].done") and pg.locator('.qcount').inner_text()=='2/3')
    pg.fill('#dlAdd','café, azúcar'); pg.press('#dlAdd','Enter'); pg.wait_for_timeout(300)
    ok(f'[{lab}] añadir a la lista', pg.locator('.qrow').count()==5)
    tap('#qUndo'); pg.wait_for_timeout(300); ok(f'[{lab}] desmarcar todos', pg.locator('.qcount').inner_text()=='0/5')
    tap('.qx'); pg.wait_for_timeout(300); ok(f'[{lab}] cerrar', pg.locator('.ov').count()==0)
    tap('#lsBtn'); pg.wait_for_timeout(300); ok(f'[{lab}] recuerda la pestaña', pg.locator('.qtitle').inner_text()=='COMPRAS')
    tap('#qOpen'); pg.wait_for_timeout(300); ok(f'[{lab}] abrir lista completa', pg.locator('h2:has-text("Compras")').count()==1)
    ok(f'[{lab}] sin scroll horizontal', pg.evaluate("document.documentElement.scrollWidth<=document.documentElement.clientWidth"))
    ok(f'[{lab}] sin errores', not errs, errs)
    ctx.close()
  b.close()
