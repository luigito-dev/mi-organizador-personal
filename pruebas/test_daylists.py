from playwright.sync_api import sync_playwright
R=[]
def ok(n,c,x=''): R.append(c); print(('PASS ' if c else 'FAIL ')+n+('' if c else ' -- '+str(x)))
with sync_playwright() as p:
  b=p.chromium.launch()
  for lab,kw in [('tel',dict(p.devices['Pixel 7'])),('pc',{'viewport':{'width':1366,'height':860}})]:
    ctx=b.new_context(**kw); pg=ctx.new_page(); errs=[]; pg.on('pageerror',lambda e: errs.append(str(e)))
    tap=(lambda s: pg.tap(s)) if lab=='tel' else (lambda s: pg.click(s))
    pg.goto('file:///home/claude/org/index.html'); pg.wait_for_timeout(300)
    pg.evaluate("S.settings.tutorialSeen=true;sheets.slice().forEach(s=>s.close());go('dia')")
    ok(f'[{lab}] sin listas no hay botón', not pg.locator('#lsBtn').is_visible())
    pg.evaluate("""S.lists.push({id:'c',name:'Compras',icon:'🛒',color:'#2e9d5b',items:[{id:'1',t:'Leche',done:false},{id:'2',t:'Pan',done:false},{id:'3',t:'Huevos',done:true}]});save();go('dia')""")
    pg.wait_for_timeout(300)
    ok(f'[{lab}] Mi Día sin tarjeta de listas', pg.locator('.view .daylists').count()==0)
    ok(f'[{lab}] botón 📋 con número', pg.locator('#lsBtn').is_visible() and pg.locator('#lsBadge').inner_text()=='2')
    for v in ['calendario','tareas','notas']:
      pg.evaluate(f"go('{v}')"); 
      if not pg.locator('#lsBtn').is_visible(): ok(f'[{lab}] botón en {v}', False)
    pg.evaluate("go('dia')"); pg.screenshot(path=f'shots/{lab}-lsbtn.png')
    tap('#lsBtn'); pg.wait_for_timeout(300)
    ok(f'[{lab}] ventana emergente con la lista abierta', pg.locator('.sheet .dlitem').count()==2)
    pg.screenshot(path=f'shots/{lab}-lspop.png')
    tap('.dlitem >> text=Leche'); pg.wait_for_timeout(500)
    ok(f'[{lab}] marcar en la ventana', pg.evaluate("S.lists[0].items[0].done") and pg.locator('#lsBadge').inner_text()=='1')
    pg.fill('#dlAdd','café, azúcar'); pg.press('#dlAdd','Enter'); pg.wait_for_timeout(300)
    ok(f'[{lab}] añadir en la ventana', pg.locator('.sheet .dlitem').count()==3 and pg.locator('#lsBadge').inner_text()=='3')
    tap('#dlOpen'); pg.wait_for_timeout(300)
    ok(f'[{lab}] abrir lista completa', pg.locator('h2:has-text("Compras")').count()==1 and pg.locator('.ov').count()==0)
    tap('#lPin'); pg.wait_for_timeout(200)
    ok(f'[{lab}] quitar del acceso rápido oculta el botón', not pg.locator('#lsBtn').is_visible())
    tap('#lPin'); pg.wait_for_timeout(200)
    ok(f'[{lab}] volver a ponerla', pg.locator('#lsBtn').is_visible())
    ok(f'[{lab}] sin scroll horizontal', pg.evaluate("document.documentElement.scrollWidth<=document.documentElement.clientWidth"))
    ok(f'[{lab}] sin errores', not errs, errs)
    ctx.close()
  b.close()
print('FALLAS', R.count(False))
