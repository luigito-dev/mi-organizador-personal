    tap=(lambda s: pg.tap(s)) if lab=='tel' else (lambda s: pg.click(s))
    pg.goto('file:///home/claude/org/index.html'); pg.wait_for_timeout(300)
    pg.evaluate("""S.settings.tutorialSeen=true;sheets.slice().forEach(s=>s.close());S.habits=[{"color":"#4a90ff","created":"2026-11-01","days":[],"goal":8,"goalOz":64,"icon":"💧","id":"w1","kind":"agua","log":{},"name":"Tomar agua","unit":"","migW":1},{"color":"#ffb627","created":"2026-11-01","days":[],"goal":30,"icon":"🚶","id":"c1","kind":"tiempo","migW":1,"log":{[todayISO()]:30},"name":"Caminar","unit":""}];go('habitos')""")
