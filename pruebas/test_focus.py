from playwright.sync_api import sync_playwright
R=[]
def ok(n,c,x=''): R.append(c); print(('PASS ' if c else 'FAIL ')+n+('' if c else ' -- '+str(x)[:200]))
with sync_playwright() as p:
  b=p.chromium.launch(args=['--autoplay-policy=no-user-gesture-required'])
  for W,H,lab in [(390,844,'tel'),(1366,860,'pc')]:
    pg=b.new_page(viewport={'width':W,'height':H}); errs=[]; pg.on('pageerror',lambda e: errs.append(str(e)))
    pg.goto('file:///home/claude/org/index.html'); pg.wait_for_timeout(300)
    pg.evaluate("S.settings.tutorialSeen=true;sheets.slice().forEach(s=>s.close());go('enfoque')"); pg.wait_for_timeout(200)
    pg.screenshot(path=f'shots/{lab}-f-idle.png')
    pg.click('#fSnd'); pg.wait_for_timeout(200)
    ok(f'[{lab}] cuadrícula de sonidos', pg.locator('[data-snd]').count()>=17)
    pg.screenshot(path=f'shots/{lab}-f-sonidos.png')
    for k in ['rain','storm','waves','stream','forest','birds','coqui','cicada','fire','wind','boil','cafe','wood','far','white','tick']:
      pg.click(f'[data-snd="{k}"]'); pg.wait_for_timeout(250)
      if pg.evaluate("Ambient.curId")!=k or not pg.evaluate("!!Ambient.cur"): ok(f'[{lab}] sonido {k}', False)
    ok(f'[{lab}] todos los sonidos suenan sin error', not errs, errs)
    pg.click('[data-snd="coqui"]'); pg.wait_for_timeout(100)
    pg.click('.sheet [data-close]'); pg.wait_for_timeout(200)
    ok(f'[{lab}] al cerrar sin reloj se calla', pg.evaluate("Ambient.curId")=='none')
    pg.click('#fGo'); pg.wait_for_timeout(600)
    ok(f'[{lab}] suena con el reloj', pg.evaluate("Ambient.curId")=='coqui')
    pg.click('#fP'); pg.wait_for_timeout(300)
    ok(f'[{lab}] pausa calla', pg.evaluate("Ambient.curId")=='none')
    pg.click('#fP'); pg.wait_for_timeout(300)
    pg.evaluate("F.endAt=Date.now()-10"); pg.wait_for_timeout(600)
    ok(f'[{lab}] descanso sin sonido', pg.evaluate("F.phase")=='short' and pg.evaluate("Ambient.curId")=='none')
    pg.click('#fEnd'); pg.wait_for_timeout(300)
    if pg.locator('[data-a="no"]').count(): pg.click('[data-a="no"]')
    # cuenta regresiva
    pg.click('[data-fm="cd"]'); pg.click('[data-cd="5"]'); pg.wait_for_timeout(100)
    ok(f'[{lab}] cuenta regresiva 05:00', '05:00' in pg.locator('.fring .c b').inner_text())
    pg.click('#fSty'); pg.wait_for_timeout(100)
    ok(f'[{lab}] estilo tarjetas', pg.locator('.fcard').count()==4)
    pg.click('#fGo'); pg.wait_for_timeout(1300)
    pg.screenshot(path=f'shots/{lab}-f-flip.png')
    pg.evaluate("F.endAt=Date.now()-10"); pg.wait_for_timeout(600)
    ok(f'[{lab}] cuenta regresiva termina y guarda', pg.evaluate("F.phase")=='idle' and pg.evaluate("S.focusLog[todayISO()].minutes")>=5)
    # cronómetro
    pg.click('[data-fm="sw"]'); pg.click('#fGo'); pg.evaluate("F.swAt-=125000"); pg.wait_for_timeout(500)
    ok(f'[{lab}] cronómetro cuenta hacia arriba', pg.evaluate("F.remain")>=125, pg.evaluate("F.remain"))
    pg.click('#fFull'); pg.wait_for_timeout(300)
    ok(f'[{lab}] pantalla completa', pg.locator('#fsOv .fcard').count()>=4)
    pg.screenshot(path=f'shots/{lab}-f-full.png')
    pg.click('#fsP'); pg.wait_for_timeout(200); ok(f'[{lab}] pausar en pantalla completa', pg.evaluate("F.paused"))
    pg.click('#fsX'); pg.wait_for_timeout(200)
    pg.click('#fEnd'); pg.wait_for_timeout(300)
    ok(f'[{lab}] cronómetro guarda minutos', pg.evaluate("S.focusLog[todayISO()].minutes")>=7)
    # actividad
    pg.click('#fSty'); pg.click('#fAct'); pg.wait_for_timeout(200); pg.click('[data-ac="🧘 Meditar"]'); pg.wait_for_timeout(200)
    ok(f'[{lab}] actividad elegida', 'Meditar' in pg.locator('#fAct').inner_text())
    pg.click('[data-fm="pomo"]'); pg.wait_for_timeout(100)
    pg.screenshot(path=f'shots/{lab}-f-final.png', full_page=True)
    ok(f'[{lab}] sin scroll horizontal', pg.evaluate("document.documentElement.scrollWidth<=document.documentElement.clientWidth"))
    ok(f'[{lab}] sin errores', not errs, errs)
    pg.close()
  b.close()
print('FALLAS', R.count(False))
